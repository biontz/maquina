#!/usr/bin/env python3
"""
gen_dredrum_flash.py - program memory bytes for Maquina Dredrum's noise wave.

The Dredrum firmware makes noise by reading its own program memory past the
sine table: pgm_read_byte(&q_sine_table[0xff + wave_pointer]), wave_pointer
0..0x1ff. Those bytes are whatever avr-gcc put there, so this script builds
both firmwares (euro-modules/dredrum/third_party/dredrum/trig, gate) with the module's own flags
and copies the 0x200 bytes from q_sine_table + 0xff. Flash past the end of
the program reads as erased (0xff), as on the chip.

The original 2014 binaries are not available; a different avr-gcc version
gives different bytes (same kind of noise). The compiler version used is
recorded in the output.

Needs avr-gcc, avr-libc, avr-binutils. `--check` only builds the firmwares
and verifies the checked-in header (used by `make test`). Writes
  euro-modules/dredrum/engine/DredrumFlash.generated.hpp   (checked in)
  build/dredrum/{trig,gate}.elf                (simavr reference, tools/dredrum_ref)

SPDX-License-Identifier: GPL-3.0-only
"""
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from layout import DREDRUM, ROOT  # noqa: E402

SRC = os.path.join(DREDRUM, "third_party", "dredrum")
OUT_DIR = os.path.join(ROOT, "build", "dredrum")
HEADER = os.path.join(DREDRUM, "engine", "DredrumFlash.generated.hpp")

MCU = "atmega48p"
FLASH_SIZE = 4096
# the firmware makefiles' compile flags; they link without --gc-sections
CFLAGS = ["-g", "-Wall", "-O2", f"-mmcu={MCU}", "-fno-exceptions", "-ffunction-sections", "-fdata-sections",
          # avr-libc dropped prog_char (deprecated since 1.8); same type, still in flash
          "-Dprog_char=const char"]
FIRMWARES = [("trig", "dredrum.c"), ("gate", "dredrum-gate.c")]
OFFSET, COUNT = 0xFF, 0x200


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout


def build(name, source):
    os.makedirs(OUT_DIR, exist_ok=True)
    obj = os.path.join(OUT_DIR, f"{name}.o")
    elf = os.path.join(OUT_DIR, f"{name}.elf")
    binf = os.path.join(OUT_DIR, f"{name}.bin")
    run(["avr-gcc", *CFLAGS, f"-I{os.path.join(SRC, name)}", "-c", os.path.join(SRC, name, source), "-o", obj])
    run(["avr-gcc", "-g", "-Wall", f"-mmcu={MCU}", "-o", elf, obj])
    # the .hex the makefile uploads: .text + .data
    run(["avr-objcopy", "-j", ".text", "-j", ".data", "-O", "binary", elf, binf])
    syms = run(["avr-nm", elf])
    m = re.search(r"^([0-9a-f]+) [tTrRdD] q_sine_table$", syms, re.M)
    if not m:
        sys.exit(f"{name}: q_sine_table not found")
    table = int(m.group(1), 16)
    with open(binf, "rb") as f:
        image = f.read()
    flash = image + b"\xff" * (FLASH_SIZE - len(image))
    start = table + OFFSET
    data = flash[start:start + COUNT]
    data += b"\xff" * (COUNT - len(data))
    return dict(elf=elf, table=table, size=len(image), data=data)


def main():
    version = run(["avr-gcc", "--version"]).splitlines()[0]
    libc = ""
    try:
        libc = run(["pacman", "-Q", "avr-libc"]).strip()
    except (OSError, subprocess.CalledProcessError):
        pass
    out = ["// GENERATED by tools/dredrum_flash/gen_dredrum_flash.py. Do not edit.",
           "// Program memory read by the Dredrum noise wave: 0x200 bytes from",
           "// q_sine_table + 0xff, per firmware build.",
           f"// Built with {version}{', ' + libc if libc else ''}.",
           "// SPDX-License-Identifier: GPL-3.0-only",
           "#pragma once",
           "#include <cstdint>",
           "",
           "namespace maquina {",
           ""]
    for name, source in FIRMWARES:
        b = build(name, source)
        print(f"{name}: program {b['size']} bytes, q_sine_table at 0x{b['table']:04x}, "
              f"noise reads 0x{b['table'] + OFFSET:04x}..0x{b['table'] + OFFSET + COUNT - 1:04x}")
        out.append(f"// {source}: program {b['size']} bytes, q_sine_table at 0x{b['table']:04x}")
        out.append(f"static const uint8_t kDredrumFlash{name.capitalize()}[{COUNT}] = {{")
        for i in range(0, COUNT, 16):
            out.append("    " + ", ".join(f"0x{x:02x}" for x in b["data"][i:i + 16]) + ",")
        out.append("};")
        out.append("")
    out.append("} // namespace maquina")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        old = open(HEADER).read() if os.path.exists(HEADER) else ""
        if old != text:
            sys.exit(f"{os.path.relpath(HEADER, ROOT)} differs from this avr-gcc's build "
                     f"(regenerate with `make dredrum-flash` if the compiler changed on purpose)")
        print(f"{os.path.relpath(HEADER, ROOT)}: up to date")
        return
    with open(HEADER, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(HEADER, ROOT)}")


if __name__ == "__main__":
    main()

    out.append(s)

    s = Script("voice_steal", 3.0)
    for i in range(14):
        s.note(0.05 * i, 1.5, 40 + 3 * i, 60 + 4 * i)
    s.at(2.0, "panic")
    s.note(2.3, 0.3, 50)
    out.append(s)

    s = Script("mono_legato_porta", 5.0)
    s.p(0, "P_POLY_MODE", 0)
    for mode, t0 in ((0, 0.0), (1, 1.6), (2, 3.2)):
        s.p(t0, "P_PORTA_MODE", mode)

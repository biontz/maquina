#!/usr/bin/env python3
"""
gen_remote_pages.py - CLAP remote-controls pages from tools/pages.py.

Hosts such as Bitwig map these pages of 8 parameters onto their remote-control
knobs and hardware controllers. The layout is the Machinista one, with the
Machinista-only "@bank"/"@patch" slots replaced by CLAP_FILL (see pages.py).

Validates every symbol against the generated parameter tables and writes
plugins/common/RemotePages.generated.hpp (compiled into the CLAP plugins,
served by patches/dpf/0002-clap-remote-controls.patch).

SPDX-License-Identifier: GPL-3.0-only
"""
import os
import re
import sys

from pages import clap_pages

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = os.path.join(ROOT, "plugins", "common", "VoiceTables.generated.hpp")
EXTRA = os.path.join(ROOT, "plugins", "common", "ExtraParams.hpp")
OUT_HPP = os.path.join(ROOT, "plugins", "common", "RemotePages.generated.hpp")
VOICES = ["kick", "tom", "snare", "cymbal", "hihat"]  # order of k_voices / MAQUINA_VOICE_INDEX
EXTRA_SYMBOLS = {v: {"note_pitch"} for v in VOICES}
EXTRA_SYMBOLS["hihat"].add("hat_mode")


def voice_symbols():
    s = open(TABLES).read()
    out = {}
    for voice in VOICES:
        m = re.search(r"static const VoiceParam k_%s_params\[\] = \{(.*?)\n\};" % voice, s, re.S)
        if not m:
            sys.exit(f"{TABLES}: no parameter table for {voice}")
        out[voice] = set(re.findall(r'^\s*\{ "(\w+)"', m.group(1), re.M)) | EXTRA_SYMBOLS[voice]
    extra = set(re.findall(r'^\s*\{ "(\w+)"', open(EXTRA).read(), re.M))
    if extra != {"note_pitch", "hat_mode"}:
        sys.exit(f"{EXTRA}: extra parameters changed ({sorted(extra)}), update EXTRA_SYMBOLS")
    return out


def main():
    symbols = voice_symbols()
    errors = 0
    out = [
        "// RemotePages.generated.hpp - generated by tools/gen_remote_pages.py from tools/pages.py, do not edit.",
        "// CLAP remote-controls pages (8 parameter symbols each), indexed like k_voices.",
        "// Include inside the DISTRHO namespace after declaring ClapRemotePage and",
        "// ClapRemotePages (see DrumPlugin.cpp; the page struct comes from patches/dpf/0002).",
        "//",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "#pragma once",
        "",
    ]
    for voice in VOICES:
        pages = clap_pages(voice)
        placed = set()
        out.append(f"static const ClapRemotePage k_{voice}_remote_pages[] = {{")
        for title, controls in pages:
            if len(controls) != 8:
                print(f"{voice}: page {title} has {len(controls)} controls, needs 8")
                errors += 1
            for c in controls:
                if c not in symbols[voice]:
                    print(f"{voice}: page {title}: unknown symbol {c}")
                    errors += 1
            placed.update(controls)
            slots = ", ".join(f'"{c}"' for c in controls)
            out.append(f'    {{ "{title}", {{ {slots} }} }},')
        out.append("};")
        missing = symbols[voice] - placed
        if missing:
            print(f"{voice}: parameters on no page: {sorted(missing)}")
            errors += 1
        print(f"{voice:7s} {len(pages)} pages")
    out.append("")
    out.append("static const ClapRemotePages k_remote_pages[] = {")
    for voice in VOICES:
        out.append(f"    {{ k_{voice}_remote_pages, sizeof(k_{voice}_remote_pages) / sizeof(k_{voice}_remote_pages[0]) }},")
    out += ["};", ""]
    if errors:
        return 1
    with open(OUT_HPP, "w") as f:
        f.write("\n".join(out))
    print(f"-> {os.path.relpath(OUT_HPP, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

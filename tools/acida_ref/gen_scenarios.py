#!/usr/bin/env python3
"""Writes the acida_ref / acida_test scenario scripts (scenarios/*.txt).
The language is described in src/main.rs. Rerun after changing this file."""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "scenarios")
TUNE, CUTOFF, RESO, ENVMOD, DECAY, ACCENT, WAVE = 2, 3, 4, 5, 6, 7, 8


def write(name, lines):
    with open(os.path.join(OUT, name + ".txt"), "w") as f:
        f.write("# generated by gen_scenarios.py\n" + "\n".join(lines) + "\n")


def tb303(name, vintage, seed, square=False):
    r = random.Random(seed)
    L = ["device tb303", f"vintage {int(vintage)}", f"param {WAVE} {int(square)}"]
    held = []
    for _ in range(160):
        a = r.random()
        if a < 0.35:
            n = r.choice([24, 36, 38, 41, 43, 48, 50, 53, 60, 67, 72, 84])
            v = r.choice([40, 99, 100, 127])
            L.append(f"on {n} {v}")
            held.append(n)
        elif a < 0.6 and held:
            n = held.pop(r.randrange(len(held)))
            L.append(f"off {n}")
        elif a < 0.85:
            c = r.choice([TUNE, CUTOFF, RESO, ENVMOD, DECAY, ACCENT])
            L.append(f"param {c} {r.randrange(128)}")
        else:
            L.append(f"param {WAVE} {r.randrange(2)}")
        L.append(f"run {r.randrange(1, 12)}")
    for n in held:
        L.append(f"off {n}")
    L.append("run 200")
    write(name, L)


def tb303_fixed():
    # a classic line: steps, slides (overlaps), accents, then a long release
    for vint in (0, 1):
        L = ["device tb303", f"vintage {vint}", f"param {CUTOFF} 40", f"param {RESO} 110",
             f"param {ENVMOD} 90", f"param {DECAY} 60", f"param {ACCENT} 100"]
        notes = [36, 36, 48, 39, 36, 43, 46, 36]
        for i, n in enumerate(notes):
            L.append(f"on {n} {127 if i % 3 == 0 else 80}")
            if i % 4 == 2:  # slide into the next note
                L.append("run 10")
                L.append(f"on {notes[(i + 1) % 8]} 80")
                L.append(f"off {n}")
                L.append("run 10")
                L.append(f"off {notes[(i + 1) % 8]}")
            else:
                L.append("run 12")
                L.append(f"off {n}")
                L.append("run 6")
        # out-of-range notes are ignored, extreme tunes
        L += [f"param {TUNE} 0", "on 0 100", "run 5", "on 127 100", "run 5", "off 127", "off 0",
              f"param {TUNE} 127", "on 127 100", "run 20", "off 127", "run 300"]
        write(f"tb303_line_{'vintage' if vint else '20'}", L)


def dist():
    L = ["device dist", "input saw 100 0.5"]
    for shape in (0, 1, 4, 17, 64, 100, 127):
        for amount in (0, 30, 70, 89, 90, 127):
            L += [f"param 2 {shape}", f"param 1 {amount}", "run 20"]
    L += ["param 0 0", "run 10", "param 0 1", "input noise 7 1.0", "run 40", "input saw 37 0.02", "run 40"]
    write("dist_sweep", L)


def pcf():
    for mode in (1, 0):
        L = ["device pcf", "input noise 3 0.3", "tickstep 8", f"param 6 {mode}"]
        for w in range(55):
            L += [f"param 4 {w}", f"param 1 {(w * 37) % 128}", f"param 2 {(w * 53) % 128}",
                  f"param 3 {(w * 29) % 128}", f"param 5 {(w * 71) % 128}", "run 48"]
        write(f"pcf_waves_{'lp' if mode == 1 else 'bp'}", L)
    L = ["device pcf", "input saw 150 0.5", "tickstep 11", "param 4 13"]
    for fr in range(0, 128, 9):
        L += [f"param 1 {fr}", "run 8", "param 6 0", "run 8", "param 6 1"]
    L += ["param 0 0", "run 5", "param 0 1", "run 30"]
    write("pcf_switches", L)


def comp():
    for dev in ("comp", "comp_stereo"):
        L = [f"device {dev}"]
        for amp, amount, th in ((0.9, 70, 64), (0.05, 127, 0), (0.6, 30, 127), (0.0, 70, 64), (1.0, 100, 20)):
            L += [f"input noise {int(amp * 100) + 5} {amp}", f"param 1 {amount}", f"param 2 {th}", "run 120"]
        L += ["param 0 0", "run 10", "param 0 1", "input saw 300 0.8", "run 400"]
        write(dev, L)


def delay():
    L = ["device delay", "input saw 64 0.5", "run 20", "input none", "run 600"]
    for steps, mode, fb, pan, tempo in ((1, 1, 127, 0, 120000), (7, 0, 60, 127, 93500), (32, 1, 100, 30, 180000),
                                         (3, 1, 80, 64, 60000)):
        L += [f"tempo {tempo}", f"param 1 {steps}", f"param 2 {mode}", f"param 3 {fb}", f"param 4 {pan}",
              "input noise 11 0.4", "run 4", "input none", "run 500"]
    L += ["param 0 0", "run 20", "param 0 1", "input saw 32 0.3", "run 10", "input none", "run 300"]
    write("delay", L)


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(".txt"):
            os.remove(os.path.join(OUT, f))
    tb303_fixed()
    for i in range(4):
        tb303(f"tb303_random_20_{i}", False, 100 + i)
        tb303(f"tb303_random_vintage_{i}", True, 200 + i, square=bool(i & 1))
    dist()
    pcf()
    comp()
    delay()


if __name__ == "__main__":
    main()

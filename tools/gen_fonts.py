#!/usr/bin/env python3
"""gen_fonts.py - turn the editor fonts into C++ headers.

Every common/ui/fonts/<Family>/<File>.ttf becomes
common/ui/fonts/<Family>/<File>.ttf.hpp holding

    static const unsigned char k_font_<id>[] = { ... };
    static const unsigned int k_font_<id>_size = ...;

with <id> = the file name in lower case, non-alphanumerics as '_'
(IBMPlexMono-Medium.ttf -> k_font_ibmplexmono_medium). The editor (common/ui/Theme.hpp)
includes only the headers its theme uses. Run after adding or replacing a font; the
headers are committed like the other generated files.

SPDX-License-Identifier: GPL-3.0-only
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "common" / "ui" / "fonts"


def ident(path):
    stem = path.name[: -len(".ttf")].replace(".subset", "")
    return "k_font_" + re.sub(r"[^a-z0-9]+", "_", stem.lower()).strip("_")


def main():
    for ttf in sorted(ROOT.glob("*/*.ttf")):
        data = ttf.read_bytes()
        name = ident(ttf)
        lines = []
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join("0x%02x" % b for b in data[i : i + 24]) + ",")
        out = ttf.with_name(ttf.name + ".hpp")
        out.write_text(
            "// %s - generated by tools/gen_fonts.py from %s/%s (SIL OFL 1.1, see LICENSE-OFL.txt)\n"
            "#pragma once\n"
            "static const unsigned char %s[] = {\n%s\n};\n"
            "static const unsigned int %s_size = %d;\n"
            % (out.name, ttf.parent.name, ttf.name, name, "\n".join(lines), name, len(data))
        )
        print("%s  %d bytes  %s" % (out.relative_to(ROOT.parent.parent.parent), len(data), name))


if __name__ == "__main__":
    main()
